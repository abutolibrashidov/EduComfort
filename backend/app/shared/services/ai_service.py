"""
AI Service for Interactive Book Processing
Handles book text extraction, unit segmentation, and exercise generation using OpenAI
"""
import os
import json
import logging
from typing import List, Dict, Any, Optional, Tuple
from datetime import datetime
from pydantic import BaseModel, Field, ValidationError

logger = logging.getLogger(__name__)

# OpenAI client setup moved to lazy loading
def get_openai_client():
    from openai import OpenAI
    from app.core.config import settings
    
    if not settings.OPENAI_API_KEY:
        logger.warning("OpenAI API key not configured.")
        return None
        
    return OpenAI(api_key=settings.OPENAI_API_KEY)



# ============================================================================
# PYDANTIC MODELS FOR AI RESPONSES
# ============================================================================

class LearningObjective(BaseModel):
    """Single learning objective"""
    objective: str


class DetectedUnit(BaseModel):
    """Unit detected by AI"""
    unit_number: int
    title: str
    start_page: int
    end_page: int
    learning_objectives: List[str] = []
    description: Optional[str] = None


class UnitSegmentationResponse(BaseModel):
    """Response from unit segmentation"""
    units: List[DetectedUnit]
    total_units: int
    confidence: float = Field(ge=0, le=100)


class ExerciseOption(BaseModel):
    """Single exercise option (for MCQ)"""
    key: str  # A, B, C, D
    text: str


class GeneratedExercise(BaseModel):
    """Single exercise generated by AI"""
    exercise_number: str
    exercise_type: str  # multiple_choice, gap_filling, true_false, short_answer, etc.
    question_text: str
    instructions: Optional[str] = None
    options: Optional[Dict[str, str]] = None  # For MCQ: {"A": "...", "B": "..."}
    correct_answer: Any  # String, list, or dict depending on type
    explanation: Optional[str] = None
    hints: Optional[List[str]] = None
    difficulty_level: Optional[str] = None
    estimated_time_seconds: Optional[int] = None


class ExerciseGenerationResponse(BaseModel):
    """Response from exercise generation"""
    exercises: List[GeneratedExercise]
    total_exercises: int
    confidence: float = Field(ge=0, le=100)


# ============================================================================
# AI SERVICE CLASS
# ============================================================================

class AIBookProcessingService:
    """
    Service for AI-powered book processing.
    Handles unit segmentation and exercise generation.
    """
    
    def __init__(self, model: str = "gpt-4", temperature: float = 0.3):
        """
        Initialize AI service.
        
        Args:
            model: OpenAI model to use (default: gpt-4)
            temperature: Sampling temperature (0.0-1.0, lower = more deterministic)
        """
        self.model = model
        self.temperature = temperature
        self.max_tokens = 4000
        
        client = get_openai_client()
        if not client:
            logger.warning("OpenAI client could not be initialized. AI processing will fail.")
    
    def segment_book_into_units(
        self, 
        book_text: str, 
        total_pages: int,
        book_title: str = ""
    ) -> Tuple[Optional[UnitSegmentationResponse], Optional[Dict[str, Any]]]:
        """
        Segment book text into logical learning units using AI.
        
        Args:
            book_text: Full text of the book
            total_pages: Total number of pages
            book_title: Title of the book (for context)
        
        Returns:
            Tuple of (UnitSegmentationResponse, metadata_dict) or (None, error_dict)
        """
        client = get_openai_client()
        if not client:
            return None, {"error": "OpenAI client not initialized"}
        
        # Truncate text if too long (keep first 30k chars)
        if len(book_text) > 30000:
            book_text = book_text[:30000] + "\n\n[... text truncated ...]"
        
        # Construct prompt
        prompt = self._build_unit_segmentation_prompt(book_text, total_pages, book_title)
        
        try:
            logger.info(f"Calling OpenAI for unit segmentation (model: {self.model})")
            start_time = datetime.utcnow()
            
            response = client.chat.completions.create(
                model=self.model,
                messages=[
                    {
                        "role": "system",
                        "content": "You are an expert educational content analyzer. You identify logical learning units in textbooks and create structured learning objectives."
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ],
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                response_format={"type": "json_object"}
            )
            
            end_time = datetime.utcnow()
            processing_time_ms = int((end_time - start_time).total_seconds() * 1000)
            
            # Parse response
            content = response.choices[0].message.content
            parsed_data = json.loads(content)
            
            # Validate with Pydantic
            result = UnitSegmentationResponse(**parsed_data)
            
            # Calculate metadata
            metadata = {
                "tokens_used": response.usage.total_tokens,
                "processing_time_ms": processing_time_ms,
                "cost_usd": self._estimate_cost(response.usage.total_tokens),
                "model": self.model,
                "finish_reason": response.choices[0].finish_reason
            }
            
            logger.info(f"Unit segmentation successful: {result.total_units} units detected")
            return result, metadata
            
        except ValidationError as e:
            logger.error(f"AI response validation failed: {e}")
            return None, {"error": "Invalid AI response format", "details": str(e)}
        
        except Exception as e:
            logger.error(f"Unit segmentation failed: {e}")
            return None, {"error": str(e)}
    
    def generate_exercises_for_unit(
        self,
        unit_text: str,
        unit_title: str,
        unit_number: int,
        target_count: int = 8
    ) -> Tuple[Optional[ExerciseGenerationResponse], Optional[Dict[str, Any]]]:
        """
        Generate interactive exercises for a unit using AI.
        
        Args:
            unit_text: Text content of the unit
            unit_title: Title of the unit
            unit_number: Unit number
            target_count: Target number of exercises to generate
        
        Returns:
            Tuple of (ExerciseGenerationResponse, metadata_dict) or (None, error_dict)
        """
        client = get_openai_client()
        if not client:
            return None, {"error": "OpenAI client not initialized"}
        
        # Truncate text if too long
        if len(unit_text) > 15000:
            unit_text = unit_text[:15000] + "\n\n[... text truncated ...]"
        
        # Construct prompt
        prompt = self._build_exercise_generation_prompt(
            unit_text, unit_title, unit_number, target_count
        )
        
        try:
            logger.info(f"Calling OpenAI for exercise generation (unit: {unit_title})")
            start_time = datetime.utcnow()
            
            response = client.chat.completions.create(
                model=self.model,
                messages=[
                    {
                        "role": "system",
                        "content": "You are an expert educational content creator. You create diverse, engaging interactive exercises that test comprehension and application of learning material."
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ],
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                response_format={"type": "json_object"}
            )
            
            end_time = datetime.utcnow()
            processing_time_ms = int((end_time - start_time).total_seconds() * 1000)
            
            # Parse response
            content = response.choices[0].message.content
            parsed_data = json.loads(content)
            
            # Validate with Pydantic
            result = ExerciseGenerationResponse(**parsed_data)
            
            # Calculate metadata
            metadata = {
                "tokens_used": response.usage.total_tokens,
                "processing_time_ms": processing_time_ms,
                "cost_usd": self._estimate_cost(response.usage.total_tokens),
                "model": self.model,
                "finish_reason": response.choices[0].finish_reason
            }
            
            logger.info(f"Exercise generation successful: {result.total_exercises} exercises created")
            return result, metadata
            
        except ValidationError as e:
            logger.error(f"AI response validation failed: {e}")
            return None, {"error": "Invalid AI response format", "details": str(e)}
        
        except Exception as e:
            logger.error(f"Exercise generation failed: {e}")
            return None, {"error": str(e)}
    
    # ========================================================================
    # PROMPT BUILDERS
    # ========================================================================
    
    def _build_unit_segmentation_prompt(
        self, 
        book_text: str, 
        total_pages: int,
        book_title: str
    ) -> str:
        """Build prompt for unit segmentation."""
        return f"""Analyze the following textbook content and identify logical learning units (chapters or lessons).

Book Title: {book_title}
Total Pages: {total_pages}

Book Content:
{book_text}

Your task:
1. Identify distinct learning units (chapters, lessons, or modules)
2. For each unit, provide:
   - unit_number (sequential, starting from 1)
   - title (clear, descriptive title)
   - start_page (estimated page number where unit begins)
   - end_page (estimated page number where unit ends)
   - learning_objectives (2-5 specific learning objectives for this unit)
   - description (brief 1-2 sentence description of what students will learn)

3. Provide an overall confidence score (0-100) for your segmentation

Return your response as JSON matching this exact structure:
{{
  "units": [
    {{
      "unit_number": 1,
      "title": "Introduction to Biology",
      "start_page": 1,
      "end_page": 15,
      "learning_objectives": [
        "Understand the basic principles of biology",
        "Identify the characteristics of living organisms"
      ],
      "description": "This unit introduces fundamental concepts in biology and the scientific method."
    }}
  ],
  "total_units": 5,
  "confidence": 85
}}

Be precise and ensure page ranges don't overlap. If you cannot determine exact pages, estimate based on content flow."""
    
    def _build_exercise_generation_prompt(
        self,
        unit_text: str,
        unit_title: str,
        unit_number: int,
        target_count: int
    ) -> str:
        """Build prompt for exercise generation."""
        return f"""Create {target_count} interactive exercises for the following learning unit.

Unit {unit_number}: {unit_title}

Unit Content:
{unit_text}

Your task:
Create {target_count} diverse exercises that test comprehension and application. Include a mix of:
- Multiple choice questions (4 options: A, B, C, D)
- Gap filling (fill-in-the-blank)
- True/False questions
- Short answer questions

For each exercise, provide:
- exercise_number (e.g., "1", "2", "3")
- exercise_type (one of: "multiple_choice", "gap_filling", "true_false", "short_answer")
- question_text (the actual question)
- instructions (optional, any special instructions)
- options (for MCQ only: {{"A": "text", "B": "text", "C": "text", "D": "text"}})
- correct_answer (the correct answer - for MCQ use "A"/"B"/"C"/"D", for gap_filling use string or array, for true_false use "true"/"false")
- explanation (why this is the correct answer)
- hints (optional, array of 1-2 hints)
- difficulty_level (one of: "beginner", "intermediate", "advanced")
- estimated_time_seconds (estimated time to complete, e.g., 60, 120)

Also provide an overall confidence score (0-100) for the quality of generated exercises.

Return your response as JSON matching this exact structure:
{{
  "exercises": [
    {{
      "exercise_number": "1",
      "exercise_type": "multiple_choice",
      "question_text": "What is the powerhouse of the cell?",
      "options": {{
        "A": "Nucleus",
        "B": "Mitochondria",
        "C": "Ribosome",
        "D": "Golgi apparatus"
      }},
      "correct_answer": "B",
      "explanation": "Mitochondria are known as the powerhouse of the cell because they produce ATP through cellular respiration.",
      "hints": ["Think about energy production", "It's an organelle"],
      "difficulty_level": "beginner",
      "estimated_time_seconds": 45
    }},
    {{
      "exercise_number": "2",
      "exercise_type": "gap_filling",
      "question_text": "The process of _____ converts light energy into chemical energy.",
      "correct_answer": "photosynthesis",
      "explanation": "Photosynthesis is the process by which plants convert light energy into chemical energy stored in glucose.",
      "difficulty_level": "beginner",
      "estimated_time_seconds": 30
    }}
  ],
  "total_exercises": {target_count},
  "confidence": 90
}}

Make exercises engaging, clear, and directly related to the unit content."""
    
    # ========================================================================
    # HELPER METHODS
    # ========================================================================
    
    def _estimate_cost(self, total_tokens: int) -> float:
        """
        Estimate cost in USD based on token usage.
        
        GPT-4 pricing (as of 2024):
        - Input: $0.03 per 1K tokens
        - Output: $0.06 per 1K tokens
        
        Using average of $0.045 per 1K tokens for estimation.
        """
        cost_per_1k = 0.045
        return (total_tokens / 1000) * cost_per_1k


# ============================================================================
# CONVENIENCE FUNCTIONS
# ============================================================================

def create_ai_service(model: str = None) -> AIBookProcessingService:
    """
    Create an AI service instance.
    
    Args:
        model: OpenAI model to use (defaults to env var or gpt-4)
    
    Returns:
        AIBookProcessingService instance
    """
    if model is None:
        model = os.getenv("OPENAI_MODEL", "gpt-3.5-turbo")
    
    return AIBookProcessingService(model=model)
